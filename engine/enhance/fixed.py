def fixed_reason(it) -> str | None:
    """재설정 불가인 이유(한국어) 또는 None."""
    if it.name == "도미네이터 펜던트" and any("크리티컬 확률" in p for p in (it.potentials or [])):
        return "PC방 도미네이터 펜던트(크확 잠재) — 스타포스·잠재 재설정 불가"
    return None


def cannot_sell(it) -> str | None:
    """팔 수 없는 템이면 이유(2026-10-17 사용자: PC방 템은 팔 수 없다). 매물 평가에서 지금 템 판매 대금을 0으로 본다."""
    if fixed_reason(it):
        return "지금 낀 PC방 도미네이터 펜던트는 팔 수 없어서 판매 대금을 0으로 계산했어요"
